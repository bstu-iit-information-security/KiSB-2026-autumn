def xtime(b: int) -> int:
    b <<= 1
    if b & 0x100:
        b ^= 0x11B          
    return b & 0xFF


def gmul(a: int, b: int) -> int:
    res = 0
    while b:
        if b & 1:
            res ^= a
        a = xtime(a)
        b >>= 1
    return res


_MUL = {k: tuple(gmul(x, k) for x in range(256)) for k in (2, 3, 9, 11, 13, 14)}


def _rcon_bytes():
    rc = [0x01]                       
    for _ in range(N_ROUNDS - 1):
        rc.append(xtime(rc[-1]))      
    return rc


RCON = _rcon_bytes()                  

_key_cache = {}


def expand_key(key: bytes):
    _check_key(key)
    key = bytes(key)
    if key in _key_cache:
        return _key_cache[key]

    w = [list(key[4 * i:4 * i + 4]) for i in range(4)]
    for i in range(4, 4 * (N_ROUNDS + 1)):
        temp = list(w[i - 1])
        if i % 4 == 0:
            temp = temp[1:] + temp[:1]                
            temp = [SBOX[b] for b in temp]             
            temp[0] ^= RCON[i // 4 - 1]                
        w.append([w[i - 4][j] ^ temp[j] for j in range(4)])

    round_keys = []
    for r in range(N_ROUNDS + 1):
        rk = []
        for c in range(4):
            rk.extend(w[4 * r + c])
        round_keys.append(rk)

    if len(_key_cache) > 64:
        _key_cache.clear()
    _key_cache[key] = round_keys
    return round_keys


def _add_round_key(s, rk):
    return [s[i] ^ rk[i] for i in range(16)]


def _sub_bytes(s):
    return [SBOX[b] for b in s]


def _inv_sub_bytes(s):
    return [INV_SBOX[b] for b in s]


def _shift_rows(s):
    out = [0] * 16
    for c in range(4):
        for r in range(4):
            out[4 * c + r] = s[4 * ((c + r) % 4) + r]
    return out


def _inv_shift_rows(s):
    out = [0] * 16
    for c in range(4):
        for r in range(4):
            out[4 * ((c + r) % 4) + r] = s[4 * c + r]
    return out


def _mix_columns(s):
    m2, m3 = _MUL[2], _MUL[3]
    out = [0] * 16
    for c in range(4):
        a0, a1, a2, a3 = s[4 * c:4 * c + 4]
        out[4 * c + 0] = m2[a0] ^ m3[a1] ^ a2 ^ a3
        out[4 * c + 1] = a0 ^ m2[a1] ^ m3[a2] ^ a3
        out[4 * c + 2] = a0 ^ a1 ^ m2[a2] ^ m3[a3]
        out[4 * c + 3] = m3[a0] ^ a1 ^ a2 ^ m2[a3]
    return out


def _inv_mix_columns(s):
    m9, m11, m13, m14 = _MUL[9], _MUL[11], _MUL[13], _MUL[14]
    out = [0] * 16
    for c in range(4):
        a0, a1, a2, a3 = s[4 * c:4 * c + 4]
        out[4 * c + 0] = m14[a0] ^ m11[a1] ^ m13[a2] ^ m9[a3]
        out[4 * c + 1] = m9[a0] ^ m14[a1] ^ m11[a2] ^ m13[a3]
        out[4 * c + 2] = m13[a0] ^ m9[a1] ^ m14[a2] ^ m11[a3]
        out[4 * c + 3] = m11[a0] ^ m13[a1] ^ m9[a2] ^ m14[a3]
    return out


def _check_key(key):
    if not isinstance(key, (bytes, bytearray)):
        raise TypeError("key must be bytes")
    if len(key) != KEY_SIZE:
        raise ValueError(f"AES-128 key must be {KEY_SIZE} bytes, got {len(key)}")


def _check_block(block, name):
    if not isinstance(block, (bytes, bytearray)):
        raise TypeError(f"{name} must be bytes")
    if len(block) != BLOCK_SIZE:
        raise ValueError(f"{name} must be exactly {BLOCK_SIZE} bytes, got {len(block)}")


def encrypt_block(pt_block: bytes, key: bytes) -> bytes:
    _check_block(pt_block, "pt_block")
    rk = expand_key(key)

    s = _add_round_key(list(pt_block), rk[0])           
    for r in range(1, N_ROUNDS):                         
        s = _sub_bytes(s)
        s = _shift_rows(s)
        s = _mix_columns(s)
        s = _add_round_key(s, rk[r])
    s = _sub_bytes(s)                                    
    s = _shift_rows(s)                                   
    s = _add_round_key(s, rk[N_ROUNDS])
    return bytes(s)


def decrypt_block(ct_block: bytes, key: bytes) -> bytes:
    _check_block(ct_block, "ct_block")
    rk = expand_key(key)

    s = _add_round_key(list(ct_block), rk[N_ROUNDS])
    for r in range(N_ROUNDS - 1, 0, -1):                 
        s = _inv_shift_rows(s)
        s = _inv_sub_bytes(s)
        s = _add_round_key(s, rk[r])
        s = _inv_mix_columns(s)
    s = _inv_shift_rows(s)
    s = _inv_sub_bytes(s)
    s = _add_round_key(s, rk[0])
    return bytes(s)
