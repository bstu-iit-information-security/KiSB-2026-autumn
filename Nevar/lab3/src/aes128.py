INV_SBOX = tuple(SBOX.index(value) for value in range(256))


def xtime(value):
    if value & 0x80:
        return ((value << 1) ^ 0x1B) & 0xFF
    return (value << 1) & 0xFF


def gmul(a, b):
    result = 0
    while b:
        if b & 1:
            result ^= a
        a = xtime(a)
        b >>= 1
    return result


def build_rcon():
    values = []
    value = 1
    for _ in range(ROUNDS):
        values.append(value)
        value = xtime(value)
    return tuple(values)


RCON = build_rcon()
MUL = {factor: tuple(gmul(value, factor) for value in range(256)) for factor in (2, 3, 9, 11, 13, 14)}
SHIFT = tuple(r + 4 * ((c + r) % 4) for c in range(4) for r in range(4))
INV_SHIFT = tuple(r + 4 * ((c - r) % 4) for c in range(4) for r in range(4))


@lru_cache(maxsize=16)
def expand_key(key):
    if len(key) != BLOCK_SIZE:
        raise ValueError("Ключ AES-128 должен содержать 16 байт")
    words = [list(key[4 * i:4 * i + 4]) for i in range(4)]
    for i in range(4, 44):
        previous = words[i - 1][:]
        if i % 4 == 0:
            previous = [SBOX[value] for value in previous[1:] + previous[:1]]
            previous[0] ^= RCON[i // 4 - 1]
        words.append([a ^ b for a, b in zip(words[i - 4], previous)])
    return tuple(
        tuple(value for word in words[4 * r:4 * r + 4] for value in word)
        for r in range(ROUNDS + 1)
    )


def add_round_key(state, round_key):
    return [a ^ b for a, b in zip(state, round_key)]


def sub_bytes(state):
    return [SBOX[value] for value in state]


def inv_sub_bytes(state):
    return [INV_SBOX[value] for value in state]


def shift_rows(state):
    return [state[index] for index in SHIFT]


def inv_shift_rows(state):
    return [state[index] for index in INV_SHIFT]


def mix_columns(state):
    m2, m3 = MUL[2], MUL[3]
    result = []
    for c in range(0, 16, 4):
        a0, a1, a2, a3 = state[c:c + 4]
        result += [
            m2[a0] ^ m3[a1] ^ a2 ^ a3,
            a0 ^ m2[a1] ^ m3[a2] ^ a3,
            a0 ^ a1 ^ m2[a2] ^ m3[a3],
            m3[a0] ^ a1 ^ a2 ^ m2[a3],
        ]
    return result


def inv_mix_columns(state):
    m9, m11, m13, m14 = MUL[9], MUL[11], MUL[13], MUL[14]
    result = []
    for c in range(0, 16, 4):
        a0, a1, a2, a3 = state[c:c + 4]
        result += [
            m14[a0] ^ m11[a1] ^ m13[a2] ^ m9[a3],
            m9[a0] ^ m14[a1] ^ m11[a2] ^ m13[a3],
            m13[a0] ^ m9[a1] ^ m14[a2] ^ m11[a3],
            m11[a0] ^ m13[a1] ^ m9[a2] ^ m14[a3],
        ]
    return result


def encrypt_block(pt_block, key):
    if len(pt_block) != BLOCK_SIZE:
        raise ValueError("Блок должен содержать 16 байт")
    round_keys = expand_key(bytes(key))
    state = add_round_key(list(pt_block), round_keys[0])
    for r in range(1, ROUNDS):
        state = add_round_key(mix_columns(shift_rows(sub_bytes(state))), round_keys[r])
    state = add_round_key(shift_rows(sub_bytes(state)), round_keys[ROUNDS])
    return bytes(state)


def decrypt_block(ct_block, key):
    if len(ct_block) != BLOCK_SIZE:
        raise ValueError("Блок должен содержать 16 байт")
    round_keys = expand_key(bytes(key))
    state = add_round_key(list(ct_block), round_keys[ROUNDS])
    for r in range(ROUNDS - 1, 0, -1):
        state = inv_sub_bytes(inv_shift_rows(state))
        state = inv_mix_columns(add_round_key(state, round_keys[r]))
    state = add_round_key(inv_sub_bytes(inv_shift_rows(state)), round_keys[0])
    return bytes(state)
